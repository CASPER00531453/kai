"""Other coding agents on the island: Codex, Copilot CLI, Gemini CLI and friends.

Each agent gets a few hook entries (or a small plugin file) that start Kai's
relay with `--agent <id>`; its sessions then show on a pill of their own.
Display only: Kai never answers a permission for these agents, they keep
asking in their own window.

Every write follows the same rules: read strictly, refuse anything unexpected,
take a dated backup that must succeed, write through a temp file. Only entries
Kai wrote are ever replaced or removed.
"""

from __future__ import annotations

import json
import os
import shutil
import time

import agents
from i18n import t

MARKER = agents.MARKER
GENERATED = "generated by Kai"

# id -> (name, files under the home folder)
AGENTS: dict[str, tuple[str, tuple[str, ...]]] = {
    "codex": ("Codex", (".codex/hooks.json",)),
    "copilot": ("GitHub Copilot CLI", (".copilot/hooks/kai.json",)),
    "gemini": ("Gemini CLI", (".gemini/settings.json",)),
    "antigravity": ("Antigravity", (".gemini/config/hooks.json",)),
    "cursor": ("Cursor Agent", (".cursor/hooks.json",)),
    "muse": ("Muse Code", (".config/muse/settings.json",)),
    "opencode": ("OpenCode", (".config/opencode/plugins/kai.js",)),
    "amp": ("Amp", (".config/amp/plugins/kai.ts",)),
    "hermes": ("Hermes Agent", (".hermes/plugins/kai/__init__.py", ".hermes/plugins/kai/plugin.yaml")),
}
PLUGINS = ("opencode", "amp", "hermes")
# The folder each agent keeps under the home folder once it has been used.
HOMES = {
    "codex": ".codex", "copilot": ".copilot", "gemini": ".gemini", "antigravity": ".gemini/antigravity",
    "cursor": ".cursor", "muse": ".config/muse", "opencode": ".config/opencode", "amp": ".config/amp", "hermes": ".hermes",
}

# No PermissionRequest anywhere: Kai shows these agents, it does not decide for them.
CODEX_EVENTS = (("SessionStart", 10), ("UserPromptSubmit", 10), ("PreToolUse", 10), ("PostToolUse", 10),
                ("Stop", 10), ("SubagentStart", 10), ("SubagentStop", 10), ("Interrupt", 3), ("SessionEnd", 3))
COPILOT_EVENTS = (("sessionStart", 10), ("userPromptSubmitted", 10), ("preToolUse", 10), ("postToolUse", 10),
                  ("agentStop", 10), ("sessionEnd", 3), ("notification", 10))
# AfterModel is left out: it fires on every response chunk.
GEMINI_EVENTS = (("SessionStart", "SessionStart", 10000), ("SessionEnd", "SessionEnd", 10000),
                 ("BeforeTool", "PreToolUse", 5000), ("AfterTool", "PostToolUse", 5000),
                 ("BeforeAgent", "UserPromptSubmit", 5000), ("AfterAgent", "Stop", 5000))
ANTIGRAVITY_TOOL = ("PreToolUse", "PostToolUse")
ANTIGRAVITY_LIFE = ("PreInvocation", "PostInvocation", "Stop")
CURSOR_EVENTS = ("sessionStart", "sessionEnd", "beforeSubmitPrompt", "preToolUse", "postToolUse", "postToolUseFailure", "stop")
MUSE_EVENTS = (("SessionStart", 10), ("UserPromptSubmit", 5), ("PreToolUse", 5), ("PostToolUse", 5), ("Stop", 5), ("SessionEnd", 3))


class Refused(Exception):
    """A config Kai will not touch; the message says why."""


# ── The relay command line ────────────────────────────────────────────────────

def _plain(path: str) -> bool:
    return bool(path) and all(ch.isalnum() or ch in "\\/:._-" for ch in path)


def command(shell: str, args: str) -> str:
    """The relay followed by args, quoted for the shell that agent runs hooks in."""
    py, script = agents._python(), agents._hook_script()
    if shell == "sh":  # Git Bash reads backslashes as escapes
        return f'"{py}" "{script}" {args}'.replace("\\", "/")
    if shell == "powershell":  # a quoted string alone is an expression: & runs it
        return "& '{}' '{}' {}".format(py.replace("'", "''"), script.replace("'", "''"), args)
    # cmd /C, or started directly: plain paths go unquoted so both work.
    if _plain(py) and _plain(script):
        return f"{py} {script} {args}"
    return f'"{py}" "{script}" {args}'


def _ours(value, agent: str) -> bool:
    return isinstance(value, str) and MARKER in value and f"--agent {agent}" in value


# ── Files ─────────────────────────────────────────────────────────────────────

def _paths(agent: str) -> list[str]:
    home = os.path.expanduser("~")
    return [os.path.join(home, *part.split("/")) for part in AGENTS[agent][1]]


def _read_json(path: str) -> dict:
    try:
        with open(path, "r", encoding="utf-8-sig") as handle:
            text = handle.read()
    except FileNotFoundError:
        return {}
    except OSError as error:
        raise Refused(t("agents.unreadable", path=path)) from error
    if not text.strip():
        return {}
    try:
        data = json.loads(text)
    except json.JSONDecodeError as error:
        raise Refused(t("agents.bad_json", path=path)) from error
    if not isinstance(data, dict):
        raise Refused(t("agents.bad_json", path=path))
    return data


def _backup(path: str) -> None:
    """A dated copy next to the file. If it cannot be taken, nothing is written."""
    if os.path.exists(path):
        shutil.copy2(path, f"{path}.kai-{time.strftime('%Y%m%d-%H%M%S')}.bak")


def _write(path: str, text: str | None, backup: bool = True) -> None:
    """Replace the file with text, or remove it when text is None."""
    if backup:
        _backup(path)
    if text is None:
        if os.path.exists(path):
            os.remove(path)
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".kai-tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    os.replace(tmp, path)


def _dump(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


# ── Claude-style hook groups ──────────────────────────────────────────────────

def _hooks_of(root: dict) -> dict:
    hooks = root.get("hooks", {})
    if not isinstance(hooks, dict):
        raise Refused(t("agents.unexpected", what='"hooks"'))
    return dict(hooks)


def _list_of(hooks: dict, event: str) -> list:
    items = hooks.get(event, [])
    if not isinstance(items, list):
        raise Refused(t("agents.unexpected", what=f'"hooks"."{event}"'))
    return list(items)


def _without_ours(groups: list, agent: str) -> list:
    """Groups ({"hooks": [{"command"}]} or a flat {"command"}) minus Kai's entries."""
    kept = []
    for group in groups:
        if not isinstance(group, dict):
            kept.append(group)
            continue
        if any(_ours(group.get(key), agent) for key in ("command", "bash", "powershell")):
            continue
        inner = group.get("hooks")
        if not isinstance(inner, list):
            kept.append(group)
            continue
        rest = [item for item in inner if not (isinstance(item, dict) and _ours(item.get("command"), agent))]
        if len(rest) == len(inner):
            kept.append(group)
        elif rest:
            kept.append({**group, "hooks": rest})
    return kept


def _groups_install(root: dict, agent: str, events: list[tuple[str, dict]]) -> dict:
    root = dict(root)
    hooks = _hooks_of(root)
    for event, group in events:
        hooks[event] = _without_ours(_list_of(hooks, event), agent) + [group]
    root["hooks"] = hooks
    return root


def _groups_uninstall(root: dict, agent: str) -> dict:
    root = dict(root)
    if "hooks" not in root:
        return root
    out = {}
    for event, value in _hooks_of(root).items():
        if isinstance(value, list):
            kept = _without_ours(value, agent)
            if kept:
                out[event] = kept
        else:
            out[event] = value
    if out:
        root["hooks"] = out
    else:
        root.pop("hooks")
    return root


def _groups_have_ours(root: dict, agent: str) -> bool:
    hooks = root.get("hooks")
    if not isinstance(hooks, dict):
        return False
    return any(isinstance(value, list) and len(_without_ours(value, agent)) != len(value) for value in hooks.values())


# ── One change per agent ──────────────────────────────────────────────────────

def _changed(agent: str, root: dict, install: bool) -> dict | None:
    """The agent's config with Kai added or removed; None removes a file that was Kai's alone."""
    if agent == "antigravity":
        root = dict(root)
        mine = MARKER in json.dumps(root.get("kai", "")) and "--agent antigravity" in json.dumps(root.get("kai", ""))
        if "kai" in root and not mine:
            raise Refused(t("agents.foreign", what='"kai"'))
        root.pop("kai", None)
        if install:
            def handler(event):
                return {"type": "command", "command": command("cmd", f"--agent antigravity {event}"), "timeout": 10}
            block = {event: [{"matcher": "*", "hooks": [handler(event)]}] for event in ANTIGRAVITY_TOOL}
            block.update({event: [handler(event)] for event in ANTIGRAVITY_LIFE})
            root["kai"] = block
        return root
    if not install:
        root = _groups_uninstall(root, agent)
        # Copilot's file is Kai's own: with nothing else in it, it goes.
        if agent == "copilot" and all(key == "version" for key in root):
            return None
        return root
    if agent == "codex":
        cmd = command("cmd", "--agent codex")
        events = [(event, {"hooks": [{"type": "command", "command": cmd, "timeout": seconds}]}) for event, seconds in CODEX_EVENTS]
        return _groups_install(root, agent, events)
    if agent == "copilot":
        events = []
        for event, seconds in COPILOT_EVENTS:
            args = f"--agent copilot {event}"
            events.append((event, {"type": "command", "bash": command("sh", args), "powershell": command("powershell", args), "timeoutSec": seconds}))
        root = _groups_install(root, agent, events)
        root["version"] = 1
        return root
    if agent == "gemini":
        events = [
            (event, {"matcher": "*", "hooks": [{"type": "command", "command": command("powershell", f"--agent gemini {said}"), "timeout": ms}]})
            for event, said, ms in GEMINI_EVENTS
        ]
        return _groups_install(root, agent, events)
    if agent == "cursor":
        cmd = command("cmd", "--agent cursor")
        root = _groups_install(root, agent, [(event, {"command": cmd}) for event in CURSOR_EVENTS])
        root.setdefault("version", 1)
        return root
    if agent == "muse":
        fresh = not root
        events = [
            (event, {"matcher": "*", "hooks": [{"type": "command", "command": command("cmd", f"--agent muse {event}"), "timeout": seconds * 1000}]})
            for event, seconds in MUSE_EVENTS
        ]
        root = _groups_install(root, agent, events)
        if fresh:
            root["schema_version"] = 1
        return root
    raise Refused(t("agents.unknown", id=agent))


def _plugin_texts(agent: str) -> list[str]:
    # A JSON string is also a valid JavaScript, TypeScript and Python one.
    py, script = json.dumps(agents._python()), json.dumps(agents._hook_script())
    if agent == "opencode":
        return [OPENCODE_PLUGIN.replace("{PY}", py).replace("{SCRIPT}", script)]
    if agent == "amp":
        return [AMP_PLUGIN.replace("{PY}", py).replace("{SCRIPT}", script)]
    return [HERMES_PLUGIN.replace("{PY}", py).replace("{SCRIPT}", script), HERMES_YAML]


# ── Public API ────────────────────────────────────────────────────────────────

def installed(agent: str) -> bool:
    """Never fails: a file that cannot be read just reads as not installed."""
    try:
        path = _paths(agent)[0]
        if agent in PLUGINS:
            with open(path, "r", encoding="utf-8") as handle:
                return GENERATED in handle.read()
        root = _read_json(path)
        if agent == "antigravity":
            text = json.dumps(root.get("kai", ""))
            return MARKER in text and "--agent antigravity" in text
        return _groups_have_ours(root, agent)
    except (OSError, Refused):
        return False


def present(agent: str) -> bool:
    """The agent looks installed on this computer: its config folder is there."""
    return os.path.isdir(os.path.join(os.path.expanduser("~"), *HOMES[agent].split("/")))


def note(agent: str) -> str:
    return t(f"agents.note.{agent}")


def status() -> list[dict]:
    return [
        {"id": agent, "name": name, "installed": installed(agent), "present": present(agent), "path": _paths(agent)[0]}
        for agent, (name, _files) in AGENTS.items()
    ]


def set_installed(agent: str, install: bool) -> str:
    """Only ever called from an explicit click. Returns what to tell the user."""
    if agent not in AGENTS:
        return t("agents.unknown", id=agent)
    if install and not agents._python():
        return t("claude.no_python")
    try:
        paths = _paths(agent)
        if agent in PLUGINS:
            for path, text in zip(paths, _plugin_texts(agent)):
                if os.path.exists(path):
                    with open(path, "r", encoding="utf-8") as handle:
                        if GENERATED not in handle.read():
                            raise Refused(t("agents.foreign", what=path))
                # Kai's own generated file: nothing of the user's to back up, and a
                # stray .bak would keep Hermes' plugin folder alive.
                _write(path, text if install else None, backup=False)
            if agent == "hermes" and not install:
                try:  # Hermes loads every folder under plugins/: an empty one goes too.
                    os.rmdir(os.path.dirname(paths[0]))
                except OSError:
                    pass
        else:
            before = _read_json(paths[0])
            after = _changed(agent, before, install)
            if after is None or after != before:
                _write(paths[0], None if after is None else _dump(after))
    except Refused as refusal:
        return str(refusal)
    except OSError as error:
        return t("agents.failed", why=str(error))
    return note(agent) if install else t("agents.removed", name=AGENTS[agent][0])


# ── Plugins: OpenCode, Amp, Hermes ────────────────────────────────────────────
# These agents load code rather than run hook commands. Every one is
# fire-and-forget: the agent never waits on Kai, and nothing happens when Kai is
# closed. None of them ever answers a permission.

OPENCODE_PLUGIN = """// Kai plugin for OpenCode — generated by Kai.
// Forwards OpenCode's events to Kai's relay (kai_hook.py), fire-and-forget:
// OpenCode never waits on it, and nothing happens when Kai is closed.
import { spawn } from 'node:child_process';

const PY = {PY};
const SCRIPT = {SCRIPT};
const EVENT_MAP = {
  'session.created': 'SessionStart',
  'session.idle': 'Stop',
  'session.error': 'StopFailure',
  'session.deleted': 'SessionEnd',
};

function forward(hook_event_name, payload) {
  try {
    const p = spawn(PY, [SCRIPT, '--agent', 'opencode'], {
      stdio: ['pipe', 'ignore', 'ignore'],
      detached: process.platform !== 'win32',
      windowsHide: true,
    });
    p.on('error', () => {});
    p.stdin.on('error', () => {});
    p.stdin.end(JSON.stringify({ hook_event_name, ...payload }) + '\\n');
    p.unref();
  } catch {}
}

export const KaiPlugin = async ({ directory } = {}) => ({
  event: async ({ event }) => {
    const hook_event_name = EVENT_MAP[event?.type];
    if (!hook_event_name) return;
    const props = event.properties || {};
    forward(hook_event_name, {
      session_id: props.sessionID || props.info?.id || '',
      cwd: directory || '',
    });
  },
  'tool.execute.before': async (input, output) => {
    forward('PreToolUse', {
      session_id: input?.sessionID || '',
      cwd: directory || '',
      tool_name: typeof input?.tool === 'string' ? input.tool : '',
      tool_input: output?.args ?? null,
    });
  },
  'tool.execute.after': async (input) => {
    forward('PostToolUse', {
      session_id: input?.sessionID || '',
      cwd: directory || '',
      tool_name: typeof input?.tool === 'string' ? input.tool : '',
    });
  },
});
"""

AMP_PLUGIN = """// Kai plugin for Amp — generated by Kai.
// Forwards Amp's events to Kai's relay (kai_hook.py), fire-and-forget and
// display only: Amp never waits on it, and it never decides anything for Amp.
import { spawn } from 'node:child_process';

const PY = {PY};
const SCRIPT = {SCRIPT};

function forward(hook_event_name: string, fields: Record<string, unknown>): void {
  try {
    const p = spawn(PY, [SCRIPT, '--agent', 'amp'], {
      stdio: ['pipe', 'ignore', 'ignore'],
      detached: process.platform !== 'win32',
      windowsHide: true,
    });
    p.on('error', () => {});
    p.stdin?.on('error', () => {});
    p.stdin?.end(JSON.stringify({ hook_event_name, ...fields }) + '\\n');
    p.unref();
  } catch {}
}

export default function (amp: any): void {
  const session = (e: any) => ({ session_id: e?.thread?.id ?? '' });
  amp.on('session.start', (e: any) => { forward('SessionStart', session(e)); });
  amp.on('agent.start', (e: any) => {
    forward('UserPromptSubmit', { ...session(e), prompt: typeof e?.message === 'string' ? e.message : '' });
  });
  // A step per tool once it has run: listening to tool.call would mean
  // returning a verdict for Amp, and Kai never makes one.
  amp.on('tool.result', (e: any) => {
    forward('PreToolUse', { ...session(e), tool_name: typeof e?.tool === 'string' ? e.tool : '', tool_input: e?.input ?? null });
  });
  amp.on('agent.end', (e: any) => { forward('Stop', { ...session(e), status: e?.status ?? '' }); });
}
"""

HERMES_PLUGIN = """# Kai plugin for Hermes Agent — generated by Kai.
# Session and tool events go to Kai's relay (kai_hook.py), fire-and-forget:
# Hermes never waits on it, and keeps every approval decision to itself.
import json, os, subprocess, threading

PY = {PY}
SCRIPT = {SCRIPT}
_current_session_id = ''


def _fire(fields):
    \"\"\"Non-blocking: start the relay and return at once. Reaps it in a thread.\"\"\"
    def _run():
        try:
            extra = {'start_new_session': True} if os.name != 'nt' else {
                'creationflags': getattr(subprocess, 'CREATE_NO_WINDOW', 0)}
            p = subprocess.Popen([PY, SCRIPT, '--agent', 'hermes'], stdin=subprocess.PIPE,
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **extra)
            p.stdin.write(json.dumps(fields).encode() + b'\\n')
            p.stdin.close()
            p.wait(timeout=5)
        except Exception:
            pass
    threading.Thread(target=_run, daemon=True).start()


def register(ctx):
    def on_session_start(**kwargs):
        global _current_session_id
        sid = kwargs.get('session_id', '')
        _current_session_id = sid
        _fire({'hook_event_name': 'SessionStart', 'session_id': sid})

    def on_session_end(**kwargs):
        # Stop comes from post_llm_call, which has the last answer.
        if kwargs.get('interrupted'):
            _fire({'hook_event_name': 'StopFailure', 'session_id': kwargs.get('session_id', '')})

    def post_llm_call(**kwargs):
        _fire({'hook_event_name': 'Stop',
               'session_id': kwargs.get('session_id', '') or _current_session_id,
               'last_assistant_message': kwargs.get('assistant_response', '')})

    def pre_tool_call(**kwargs):
        _fire({'hook_event_name': 'PreToolUse',
               'session_id': kwargs.get('session_id', '') or _current_session_id,
               'tool_name': kwargs.get('tool_name', ''),
               'tool_input': kwargs.get('args') or {}})

    def post_tool_call(**kwargs):
        _fire({'hook_event_name': 'PostToolUse',
               'session_id': kwargs.get('session_id', '') or _current_session_id,
               'tool_name': kwargs.get('tool_name', '')})

    ctx.register_hook('on_session_start', on_session_start)
    ctx.register_hook('on_session_end', on_session_end)
    ctx.register_hook('post_llm_call', post_llm_call)
    ctx.register_hook('pre_tool_call', pre_tool_call)
    ctx.register_hook('post_tool_call', post_tool_call)
"""

